// Writes src/light-theme.css: the light look, built from the colour classes the app actually uses.
// Run again after adding new colour classes:   node tools/gen-light-theme.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');

// Light palette (1.8): warm cream page #F4EFE4, lighter cream cards #FCFAF3, deep forest green #26402F,
// pale sage #DDE3D3 and a green-black ink. Cards are lifted by soft shadows (see light-design.css), not outlines.
// Dark shade -> light colour (the neutral scale is flipped).
const NEUTRAL = {
  950: [244, 239, 228], 900: [252, 250, 243], 800: [231, 226, 211], 700: [212, 206, 188],
  600: [99, 105, 91], 500: [86, 92, 79], 400: [74, 81, 71], 300: [58, 66, 58],
  200: [40, 52, 45], 100: [27, 43, 34], 50: [20, 33, 26],
};
const INK = [27, 43, 34]; // what "white" text becomes (green-black ink, #1B2B22)
// Accent text that is pale on dark needs to be deeper on light.
const ACCENT = {
  green: { 100: '#1b5a28', 200: '#1b5a28', 300: '#1f6b2e', 400: '#1f6b2e', 500: '#1f6b2e' },
  amber: { 100: '#78350f', 200: '#92400e', 300: '#a04a08', 400: '#a04a08', 500: '#a04a08' },
  red: { 100: '#7f1d1d', 200: '#991b1b', 300: '#b91c1c', 400: '#c0211f', 500: '#c0211f' },
  sky: { 300: '#0369a1', 400: '#0284c7', 500: '#0284c7' },
};
const VARIANT = {
  '': '', 'hover:': ':hover', 'active:': ':active', 'focus:': ':focus', 'focus-visible:': ':focus-visible',
  'disabled:hover:': ':disabled:hover', 'placeholder:': '::placeholder',
};
const PROP = {
  bg: 'background-color', text: 'color', border: 'border-color', stroke: 'stroke', fill: 'fill',
  'ring-offset': '--tw-ring-offset-color',
};

const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.tsx'));
const rx = /(?<![\w:/-])((?:[a-z-]+:)*)(bg|text|border|stroke|fill|ring-offset)-(neutral|white|green|amber|red|sky)(?:-(\d{2,3}))?(?:\/(\d{1,3}))?(?![\w-])/g;
const seen = new Map();
for (const f of files) {
  for (const m of fs.readFileSync(path.join(srcDir, f), 'utf8').matchAll(rx)) seen.set(m[0], m);
}

const rgb = (c, a) => `rgb(${c[0]} ${c[1]} ${c[2]}${a !== undefined && a < 1 ? ` / ${a}` : ''})`;
const esc = (s) => s.replace(/[:/.[\]]/g, '\\$&');
const rules = [];
const problems = [];
for (const [cls, m] of [...seen].sort((a, b) => a[0].localeCompare(b[0]))) {
  const [, variant, prop, color, shadeRaw, alphaRaw] = m;
  if (!(variant in VARIANT)) { problems.push(`unknown variant in ${cls}`); continue; }
  const shade = shadeRaw ? Number(shadeRaw) : undefined;
  const alpha = alphaRaw ? Number(alphaRaw) / 100 : undefined;
  let value;
  if (color === 'neutral') {
    if (prop === 'text' && shade === 950) continue; // dark text that sits on bright fills stays dark
    const base = NEUTRAL[shade];
    if (!base) { problems.push(`no light colour for ${cls}`); continue; }
    if (prop === 'bg' && shade === 900 && alpha !== undefined) value = rgb(base, Math.min(1, alpha * 2));
    else if (prop === 'border') value = rgb(base);
    else value = rgb(base, alpha);
  } else if (color === 'white') {
    if (prop !== 'text') continue; // white knobs and thumbs stay white
    value = rgb(INK, alpha);
  } else {
    if (prop !== 'text') continue; // fills and borders in colour read fine on light
    const hex = ACCENT[color]?.[shade];
    if (!hex) continue; // already deep enough
    value = hex;
  }
  rules.push(`html[data-theme='light'] .${esc(cls)}${VARIANT[variant]} { ${PROP[prop]}: ${value}; }`);
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

// Light-theme colour decisions that need more than one class at a time.
const L = "html[data-theme='light']";
const EXTRA = `
/* Primary buttons and selected tabs: deep forest green with cream text. */
${L} .bg-green-500.text-neutral-950, ${L} .bg-green-500.text-black { background-color: #26402f; color: #fcfaf3; }
${L} .bg-green-500.text-neutral-950:hover, ${L} .hover\\:bg-green-400.bg-green-500:hover { background-color: #34543f; }
/* Soft green surfaces use pale sage-green. */
${L} .bg-green-500\\/10, ${L} .bg-green-500\\/15 { background-color: #e3ebd9; }
${L} .bg-green-500\\/30 { background-color: #cddcc0; }
${L} .border-green-500\\/30, ${L} .border-green-500\\/40 { border-color: #b7cba8; }
${L} .ring-green-500\\/30 { --tw-ring-color: #b7cba8; }
/* Green marks and fills that are not buttons (toggles, rings, dots, focus lines): forest green. */
${L} .bg-green-500 { background-color: #2f5d41; }
${L} .border-green-500, ${L} .border-green-400, ${L} .focus\\:border-green-500:focus { border-color: #2f5d41; }
${L} .stroke-green-500, ${L} .stroke-green-400 { stroke: #2f5d41; }
${L} .accent-green-500 { accent-color: #2f5d41; }
${L} .ring-green-500 { --tw-ring-color: #2f5d41; }
`;

const css = `/* GENERATED by tools/gen-light-theme.mjs - do not edit by hand. */
/* The light look. It only applies when <html data-theme="light">. */
html[data-theme='light'] { color-scheme: light; }
html[data-theme='light'] .bg-black\\/65 { background-color: rgb(30 42 33 / 0.42); }
html[data-theme='light'] .shadow-black\\/50 { --tw-shadow-color: rgb(38 64 47 / 0.18); --tw-shadow: var(--tw-shadow-colored); }
${rules.join('\n')}
${EXTRA}
`;
fs.writeFileSync(path.join(srcDir, 'light-theme.css'), css);
console.log(`light-theme.css: ${rules.length} rules from ${seen.size} colour classes`);
