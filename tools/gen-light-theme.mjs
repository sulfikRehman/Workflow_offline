// Writes src/light-theme.css: the light look, built from the colour classes the app actually uses.
// Run again after adding new colour classes:   node tools/gen-light-theme.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');

// Dark shade -> light colour (the neutral scale is flipped; cards become white on a soft grey page).
const NEUTRAL = {
  950: [245, 245, 245], 900: [255, 255, 255], 800: [229, 229, 229], 700: [212, 212, 212],
  600: [140, 140, 140], 500: [100, 100, 100], 400: [82, 82, 82], 300: [64, 64, 64],
  200: [38, 38, 38], 100: [23, 23, 23], 50: [10, 10, 10],
};
const INK = [10, 10, 10]; // what "white" text becomes
// Accent text that is pale on dark needs to be deeper on light.
const ACCENT = {
  green: { 100: '#14532d', 200: '#14532d', 300: '#166534', 400: '#166534', 500: '#15803d' },
  amber: { 100: '#78350f', 200: '#92400e', 300: '#b45309', 400: '#b45309', 500: '#b45309' },
  red: { 100: '#7f1d1d', 200: '#991b1b', 300: '#b91c1c', 400: '#dc2626', 500: '#dc2626' },
  sky: { 300: '#0369a1', 400: '#0284c7', 500: '#0284c7' },
};
const VARIANT = {
  '': '', 'hover:': ':hover', 'active:': ':active', 'focus:': ':focus', 'focus-visible:': ':focus-visible',
  'disabled:hover:': ':disabled:hover', 'placeholder:': '::placeholder',
};
const PROP = {
  bg: 'background-color', text: 'color', border: 'border-color', stroke: 'stroke', fill: 'fill',
  'ring-offset': '--tw-ring-offset-color',
};

const files = fs.readdirSync(srcDir).filter((f) => f.endsWith('.tsx'));
const rx = /(?<![\w:/-])((?:[a-z-]+:)*)(bg|text|border|stroke|fill|ring-offset)-(neutral|white|green|amber|red|sky)(?:-(\d{2,3}))?(?:\/(\d{1,3}))?(?![\w-])/g;
const seen = new Map();
for (const f of files) {
  for (const m of fs.readFileSync(path.join(srcDir, f), 'utf8').matchAll(rx)) seen.set(m[0], m);
}

const rgb = (c, a) => `rgb(${c[0]} ${c[1]} ${c[2]}${a !== undefined && a < 1 ? ` / ${a}` : ''})`;
const esc = (s) => s.replace(/[:/.[\]]/g, '\\$&');
const rules = [];
const problems = [];
for (const [cls, m] of [...seen].sort((a, b) => a[0].localeCompare(b[0]))) {
  const [, variant, prop, color, shadeRaw, alphaRaw] = m;
  if (!(variant in VARIANT)) { problems.push(`unknown variant in ${cls}`); continue; }
  const shade = shadeRaw ? Number(shadeRaw) : undefined;
  const alpha = alphaRaw ? Number(alphaRaw) / 100 : undefined;
  let value;
  if (color === 'neutral') {
    if (prop === 'text' && shade === 950) continue; // dark text that sits on bright fills stays dark
    const base = NEUTRAL[shade];
    if (!base) { problems.push(`no light colour for ${cls}`); continue; }
    if (prop === 'bg' && shade === 900 && alpha !== undefined) value = rgb(base, Math.min(1, alpha * 2));
    else if (prop === 'border') value = rgb(base);
    else value = rgb(base, alpha);
  } else if (color === 'white') {
    if (prop !== 'text') continue; // white knobs and thumbs stay white
    value = rgb(INK, alpha);
  } else {
    if (prop !== 'text') continue; // fills and borders in colour read fine on light
    const hex = ACCENT[color]?.[shade];
    if (!hex) continue; // already deep enough
    value = hex;
  }
  rules.push(`html[data-theme='light'] .${esc(cls)}${VARIANT[variant]} { ${PROP[prop]}: ${value}; }`);
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const css = `/* GENERATED by tools/gen-light-theme.mjs - do not edit by hand. */
/* The light look. It only applies when <html data-theme="light">. */
html[data-theme='light'] { color-scheme: light; }
html[data-theme='light'] .bg-black\\/65 { background-color: rgb(0 0 0 / 0.4); }
html[data-theme='light'] .shadow-black\\/50 { --tw-shadow-color: rgb(0 0 0 / 0.16); --tw-shadow: var(--tw-shadow-colored); }
${rules.join('\n')}
`;
fs.writeFileSync(path.join(srcDir, 'light-theme.css'), css);
console.log(`light-theme.css: ${rules.length} rules from ${seen.size} colour classes`);
